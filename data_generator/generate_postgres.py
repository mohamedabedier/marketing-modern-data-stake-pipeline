"""Generate related CRM and ecommerce data in PostgreSQL.

Run:
    python generate_postgres.py
It creates the schema once, seeds stable customers, then creates new orders
and order items every interval. IDs are deterministic for customers/products;
order IDs are generated by PostgreSQL.
"""
import os
import random
import time
from datetime import datetime, timezone
from decimal import Decimal
import psycopg2
from psycopg2.extras import execute_values
from dotenv import load_dotenv

load_dotenv()
random.seed(int(os.getenv("DATA_SEED", "42")))

DB = {
    "host": os.getenv("POSTGRES_HOST", "localhost"),
    "port": int(os.getenv("POSTGRES_PORT", "5432")),
    "dbname": os.getenv("POSTGRES_DB", "marketing_crm"),
    "user": os.getenv("POSTGRES_USER", "postgres"),
    "password": os.getenv("POSTGRES_PASSWORD", "postgres"),
}
INTERVAL_SECONDS = int(os.getenv("POSTGRES_INTERVAL_SECONDS", "60"))
CUSTOMER_COUNT = int(os.getenv("CUSTOMER_COUNT", "100"))
BATCH_ORDERS = int(os.getenv("ORDERS_PER_BATCH", "5"))

COUNTRIES = ["EG", "SA", "AE", "JO"]
CHANNELS = ["paid_social", "paid_search", "organic", "email", "direct"]
PRODUCTS = [
    (1001, "Wireless Mouse", Decimal("450.00")),
    (1002, "Mechanical Keyboard", Decimal("1800.00")),
    (1003, "USB-C Hub", Decimal("950.00")),
    (1004, "Laptop Stand", Decimal("700.00")),
    (1005, "Headphones", Decimal("1250.00")),
]

def connect():
    return psycopg2.connect(**DB)

def create_schema(conn):
    with conn, conn.cursor() as cur:
        cur.execute("""
        CREATE TABLE IF NOT EXISTS customers (
            customer_id BIGINT PRIMARY KEY,
            first_name TEXT NOT NULL,
            email TEXT NOT NULL UNIQUE,
            created_at TIMESTAMPTZ NOT NULL,
            country_code VARCHAR(2) NOT NULL,
            acquisition_channel TEXT NOT NULL,
            anonymous_id TEXT NOT NULL UNIQUE,
            updated_at TIMESTAMPTZ NOT NULL
        );
        CREATE TABLE IF NOT EXISTS orders (
            order_id BIGSERIAL PRIMARY KEY,
            customer_id BIGINT NOT NULL REFERENCES customers(customer_id),
            order_timestamp TIMESTAMPTZ NOT NULL,
            order_status TEXT NOT NULL,
            currency VARCHAR(3) NOT NULL,
            subtotal_amount NUMERIC(12,2) NOT NULL,
            discount_amount NUMERIC(12,2) NOT NULL,
            shipping_amount NUMERIC(12,2) NOT NULL,
            tax_amount NUMERIC(12,2) NOT NULL,
            total_amount NUMERIC(12,2) NOT NULL,
            updated_at TIMESTAMPTZ NOT NULL
        );
        CREATE TABLE IF NOT EXISTS order_items (
            order_item_id BIGSERIAL PRIMARY KEY,
            order_id BIGINT NOT NULL REFERENCES orders(order_id),
            product_id BIGINT NOT NULL,
            product_name TEXT NOT NULL,
            quantity INTEGER NOT NULL,
            unit_price NUMERIC(12,2) NOT NULL,
            discount_amount NUMERIC(12,2) NOT NULL,
            line_total NUMERIC(12,2) NOT NULL
        );
        CREATE INDEX IF NOT EXISTS idx_orders_customer ON orders(customer_id);
        CREATE INDEX IF NOT EXISTS idx_orders_timestamp ON orders(order_timestamp);
        """)

def seed_customers(conn):
    now = datetime.now(timezone.utc)
    rows = []
    for cid in range(1, CUSTOMER_COUNT + 1):
        rows.append((
            cid, f"Customer{cid:03d}", f"customer{cid:03d}@example.test",
            now, random.choice(COUNTRIES), random.choice(CHANNELS),
            f"anon_{cid:06d}", now
        ))
    with conn, conn.cursor() as cur:
        execute_values(cur, """
            INSERT INTO customers
            (customer_id, first_name, email, created_at, country_code,
             acquisition_channel, anonymous_id, updated_at)
            VALUES %s
            ON CONFLICT (customer_id) DO NOTHING
        """, rows)

def create_order_batch(conn):
    now = datetime.now(timezone.utc)
    with conn, conn.cursor() as cur:
        cur.execute("SELECT customer_id FROM customers ORDER BY customer_id")
        customer_ids = [r[0] for r in cur.fetchall()]
        for _ in range(BATCH_ORDERS):
            customer_id = random.choice(customer_ids)
            chosen = random.sample(PRODUCTS, k=random.randint(1, 3))
            items = []
            subtotal = Decimal("0.00")
            for product_id, product_name, price in chosen:
                qty = random.randint(1, 2)
                line = price * qty
                subtotal += line
                items.append((product_id, product_name, qty, price, line))
            discount = (subtotal * Decimal(random.choice(["0", "0.05", "0.10"]))).quantize(Decimal("0.01"))
            shipping = Decimal("0.00") if subtotal >= Decimal("2000") else Decimal("60.00")
            tax = ((subtotal - discount) * Decimal("0.14")).quantize(Decimal("0.01"))
            total = subtotal - discount + shipping + tax
            status = random.choices(["completed", "pending", "cancelled"], weights=[85, 10, 5])[0]
            cur.execute("""
                INSERT INTO orders
                (customer_id, order_timestamp, order_status, currency, subtotal_amount,
                 discount_amount, shipping_amount, tax_amount, total_amount, updated_at)
                VALUES (%s,%s,%s,'EGP',%s,%s,%s,%s,%s,%s)
                RETURNING order_id
            """, (customer_id, now, status, subtotal, discount, shipping, tax, total, now))
            order_id = cur.fetchone()[0]
            item_rows = []
            for product_id, product_name, qty, price, line in items:
                item_discount = (line * (discount / subtotal)).quantize(Decimal("0.01")) if subtotal else Decimal("0")
                item_rows.append((order_id, product_id, product_name, qty, price, item_discount, line-item_discount))
            execute_values(cur, """
                INSERT INTO order_items
                (order_id, product_id, product_name, quantity, unit_price, discount_amount, line_total)
                VALUES %s
            """, item_rows)
        print(f"[PostgreSQL] Created {BATCH_ORDERS} orders at {now.isoformat()}")

def main():
    print("[PostgreSQL] Connecting...")
    conn = connect()
    create_schema(conn)
    seed_customers(conn)
    print(f"[PostgreSQL] Schema ready; seeded up to {CUSTOMER_COUNT} stable customers.")
    while True:
        create_order_batch(conn)
        time.sleep(INTERVAL_SECONDS)

if __name__ == "__main__":
    main()
